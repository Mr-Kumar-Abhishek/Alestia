const fn arcsec_to_rad(arcsec: f64) -> f64 {
    deg_to_rad(arcsec / 3600.0)
}

const fn milliarcsec_to_rad(mas: f64) -> f64 {
    deg_to_rad(mas / 3_600_000.0)
}

const fn microarcsec_to_rad(uas: f64) -> f64 {
    deg_to_rad(uas / 3_600_000_000.0)
}

/// Calculate Earth nutation angles using the IAU 2000B model (`77` lunisolar terms + planetary offset).
///
/// `centuries` is Julian centuries (`(tt - J2000) / 36525.0`).
#[must_use]
pub fn nutation_iau2000b(centuries: f64) -> NutationAngles {
    let t2 = centuries * centuries;
    let t3 = t2 * centuries;
    let t4 = t3 * centuries;

    let mean_anom_moon = arcsec_to_rad(
        134.963_402_51 + 1_717_915_923.217_8 * centuries + 31.879_2 * t2 + 0.051_635 * t3
            - 0.000_244_7 * t4,
    );
    let mean_anom_sun = arcsec_to_rad(
        357.529_109_18 + 129_596_581.048_1 * centuries - 0.553_2 * t2 + 0.000_136 * t3
            - 0.000_011_49 * t4,
    );
    let arg_lat_moon = arcsec_to_rad(
        93.272_090_62 + 1_739_527_262.847_8 * centuries - 12.751_2 * t2 - 0.001_037 * t3
            + 0.000_004_17 * t4,
    );
    let elongation_moon = arcsec_to_rad(
        29.785_019_547 + 1_602_961_601.209 * centuries - 6.370_6 * t2 + 0.006_593 * t3
            - 0.000_031_69 * t4,
    );
    let node_moon = arcsec_to_rad(
        125.044_555_01 - 6_962_890.543_1 * centuries + 7.472_2 * t2 + 0.007_702 * t3
            - 0.000_059_39 * t4,
    );

    let mut obliquity_sum = 0.0_f64;
    let mut longitude_sum = 0.0_f64;

    for term in &IAU2000B_TABLE {
        let arg = mean_anom_moon * f64::from(term.m_moon_anom)
            + mean_anom_sun * f64::from(term.m_sun_anom)
            + arg_lat_moon * f64::from(term.m_arg_lat)
            + elongation_moon * f64::from(term.m_elongation)
            + node_moon * f64::from(term.m_node);
        let (sin_arg, cos_arg) = arg.sin_cos();

        longitude_sum +=
            (term.lon_sin + term.lon_t_sin * centuries) * sin_arg + term.lon_cos * cos_arg;
        obliquity_sum +=
            (term.obl_cos + term.obl_t_cos * centuries) * cos_arg + term.obl_sin * sin_arg;
    }

    NutationAngles {
        obliquity: microarcsec_to_rad(obliquity_sum * 0.1) + milliarcsec_to_rad(-0.135),
        longitude: microarcsec_to_rad(longitude_sum * 0.1) + milliarcsec_to_rad(0.388),
    }
}

#[cfg(test)]
mod tests {
    use alestia_math::rad_to_deg;

    use super::nutation_iau2000b;

    #[test]
    fn iau2000b_nutation_stays_within_iers_physical_amplitudes() -> Result<(), String> {
        for centuries in [-1.0, 0.0, 0.25, 1.0] {
            let angles = nutation_iau2000b(centuries);
            let lon_arcsec = rad_to_deg(angles.longitude) * 3600.0;
            let obl_arcsec = rad_to_deg(angles.obliquity) * 3600.0;
            if lon_arcsec.abs() >= 25.0 || obl_arcsec.abs() >= 15.0 {
                return Err(format!(
                    "Nutation out of physical range at T={centuries}: dpsi={lon_arcsec}\", deps={obl_arcsec}\""
                ));
            }
        }
        Ok(())
    }
}
